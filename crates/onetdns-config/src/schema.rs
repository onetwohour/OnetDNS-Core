    /** @brief 모든 항목에 실제 설명이 있는지. 대충 채운 문구가 없어야 한다. */
    fn localized_copy_covers_every_field_without_generic_fallbacks() {
        assert_eq!(FIELD_COPY.len(), FIELDS.len());
        for fd in fields() {
            let copy = field_copy(fd.key);
            assert_eq!(copy.key, fd.key);
            for (language, label, description) in [
                ("ko", copy.label_ko, copy.description_ko),
                ("en", copy.label_en, copy.description_en),
                ("ja", copy.label_ja, copy.description_ja),
                ("zh", copy.label_zh, copy.description_zh),
            ] {
                assert!(
                    !label.trim().is_empty(),
                    "{} {language} label missing",
                    fd.key
                );
                assert!(
                    description.trim().len() >= 8,
                    "{} {language} description is too short",
                    fd.key
                );
            }
            assert!(
                !copy.description_ko.contains("관련 보안·성능 영향을 확인"),
                "{} still uses a generic Korean description",
                fd.key
            );
            assert!(
                !copy
                    .description_en
                    .contains("Value, address, or path used by"),
                "{} still uses a generic English description",
                fd.key
            );
        }
    }

